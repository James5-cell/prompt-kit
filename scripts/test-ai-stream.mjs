import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const output = ts.transpileModule(readFileSync('src/services/aiTestClient.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { parseSSEResponse } = await import('data:text/javascript;base64,' + Buffer.from(output).toString('base64'));
const encode = new TextEncoder();
const response = (chunks) => new Response(new ReadableStream({ start(controller) { chunks.forEach(chunk => controller.enqueue(encode.encode(chunk))); controller.close(); } }), { headers: { 'Content-Type': 'text/event-stream' } });
const updates = [];
const result = await parseSSEResponse(response(['data: {"te', 'xt":"你好"}\r\n\r\ndata:{"text":"世界"}\n', 'data: {"metadata":{"modelUsed":"test","finishReason":"stop"}}']), '', '', text => updates.push(text));
assert.equal(result.text, '你好世界');
assert.equal(result.modelUsed, 'test');
assert.deepEqual(updates, ['你好', '你好世界']);
await assert.rejects(parseSSEResponse(response(['data: {"text":"partial"}\n', 'data: {"error":"quota exceeded"}']), '', ''), /quota exceeded/);
await assert.rejects(parseSSEResponse(response(['data: {"text":"partial"}\n']), '', ''), /连接提前中断/);
await assert.rejects(parseSSEResponse(response(['data: invalid\n']), '', ''), /响应格式异常/);
await assert.rejects(parseSSEResponse(response(['data: {"metadata":{}}\n']), '', ''), /模型未返回内容/);
await assert.rejects(parseSSEResponse(new Response('{"error":"Unavailable"}', { status: 503, headers: { 'content-type': 'application/json' } }), '', ''), /Unavailable/);
const searchOutput = ts.transpileModule(readFileSync('src/utils/promptSearch.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { promptSearchScore } = await import('data:text/javascript;base64,' + Buffer.from(searchOutput).toString('base64'));
const prompt = { title: 'Translation 工具', content: '词典 input', tagNames: ['English'], inputHint: '粘贴文本' };
assert.ok(promptSearchScore(prompt, 'ＴＲＡＮＳＬＡＴＩＯＮ English') > 0);
assert.equal(promptSearchScore(prompt, 'translation missing'), 0);
assert.ok(promptSearchScore(prompt, 'translation') > promptSearchScore(prompt, '词典'));
console.log('Passed: split SSE packets, CRLF, final metadata, trailing errors, interrupted and empty streams, HTTP errors, and search relevance.');
