import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const compile = source => ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const url = source => `data:text/javascript;base64,${Buffer.from(source).toString('base64')}`;
const configUrl = url(compile(await readFile(new URL('../src/mascot.config.ts', import.meta.url), 'utf8')));
const engineSource = compile(await readFile(new URL('../src/mascot/engine.ts', import.meta.url), 'utf8')).replace('"../mascot.config"', JSON.stringify(configUrl));
const { MascotEngine } = await import(url(engineSource));
const engine = new MascotEngine(null, 0, () => 0.5);
const mode = (at, signals = []) => { engine.tick(at, signals, false); return engine.snapshot().mode; };
for (const at of [0, 100, 200]) mode(at, [{ type: 'tap', at, anchorX: 78 }]);
assert.equal(engine.snapshot().mode, 'shy');
assert.equal(mode(1180), 'shy_hide');
assert.equal(mode(1280, [{ type: 'hover', anchorX: 78 }, { type: 'scroll' }]), 'shy_hide');
assert.equal(mode(1830), 'shy_wait');
assert.equal(mode(4230), 'rest');
assert.equal(mode(4300, [{ type: 'document_hidden', value: true }]), 'guarded');
assert.equal(mode(8000, [{ type: 'document_hidden', value: false }]), 'rest');
console.log('7 mascot recovery and visibility checks passed.');
